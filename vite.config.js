import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { join, relative, resolve } from 'node:path'

// 正式版：/finance-tracker/；預覽版（FT_PREVIEW=1，由 preview 分支建置）：/finance-tracker/preview/
// 預覽版與正式版同網域、讀寫同一本帳，只是另一套畫面，加到主畫面是第二個圖示。
const PREVIEW = process.env.FT_PREVIEW === '1'
const ROOT_BASE = '/finance-tracker/'
const BASE = PREVIEW ? ROOT_BASE + 'preview/' : ROOT_BASE
const PREVIEW_PREFIX = ROOT_BASE + 'preview/'

// 預覽版：改寫 manifest（名稱、網址範圍）與 iOS 主畫面名稱，讓它成為獨立的第二個 App
function previewManifestPlugin() {
  return {
    name: 'preview-manifest',
    apply: 'build',
    closeBundle() {
      if (!PREVIEW) return
      const distDir = resolve(__dirname, 'dist')
      const mf = join(distDir, 'manifest.webmanifest')
      const m = JSON.parse(readFileSync(mf, 'utf8'))
      const fix = (u) => (typeof u === 'string' && u.startsWith(ROOT_BASE) ? BASE + u.slice(ROOT_BASE.length) : u)
      m.name = '記帳 2.0 預覽'
      m.short_name = '記帳2.0'
      m.id = BASE
      m.start_url = BASE
      m.scope = BASE
      m.icons = m.icons.map((i) => ({ ...i, src: fix(i.src) }))
      m.shortcuts = (m.shortcuts || []).map((sc) => ({
        ...sc, url: fix(sc.url), icons: (sc.icons || []).map((i) => ({ ...i, src: fix(i.src) })),
      }))
      writeFileSync(mf, JSON.stringify(m, null, 2))
      const html = join(distDir, 'index.html')
      writeFileSync(html, readFileSync(html, 'utf8')
        .replace('content="記帳助手"', 'content="記帳2.0"')
        .replace('<title>記帳助手</title>', '<title>記帳 2.0 預覽</title>'))
    }
  }
}

// GitHub Pages 對所有檔案只回 cache-control: max-age=600，超過 10 分鐘後每次開啟
// 都得重新下載整包 JS/CSS，開啟速度因此受網路影響。這個外掛在 build 完成後產生
// dist/sw.js：安裝時把所有產物預快取，之後開啟一律先用快取（App Shell 秒開），
// 新版部署則由 Service Worker 更新機制在背景下載、於下次進入時套用。
function swPrecachePlugin() {
  return {
    name: 'sw-precache',
    apply: 'build',
    closeBundle() {
      // 預覽版不註冊 Service Worker（每次開啟都拿最新版，方便試用）
      if (PREVIEW) return
      const distDir = resolve(__dirname, 'dist')
      const files = []
      const walk = (dir) => {
        for (const name of readdirSync(dir)) {
          const p = join(dir, name)
          if (statSync(p).isDirectory()) walk(p)
          else files.push(p)
        }
      }
      walk(distDir)

      const hash = createHash('md5')
      const urls = []
      for (const f of files.sort()) {
        const rel = relative(distDir, f).split('\\').join('/')
        if (rel === 'sw.js') continue
        hash.update(rel)
        hash.update(readFileSync(f))
        // index.html 以目錄網址（BASE）為快取鍵，對應瀏覽器的 navigation request
        urls.push(rel === 'index.html' ? BASE : BASE + rel)
      }
      // 時間戳前綴（秒、定寬）讓快取名稱可依字典序排出新舊
      const version = `${Math.floor(Date.now() / 1000)}-${hash.digest('hex').slice(0, 10)}`

      const sw = `// generated by vite.config.js (sw-precache) — do not edit
const CACHE = 'ft-shell-${version}';
const BASE = '${BASE}';
const PREVIEW_PREFIX = '${PREVIEW_PREFIX}';
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      // cache: 'no-cache' — 安裝時繞過瀏覽器 HTTP 快取（GitHub Pages max-age=600），
      // 避免剛部署完的短暫視窗內把舊版 index.html 存進預快取
      .then((cache) => cache.addAll(PRECACHE.map((u) => new Request(u, { cache: 'no-cache' }))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => {
        // 保留「最新的前一代」快取：新版 SW 接管瞬間，舊頁面可能仍在載入
        // 舊版資源（部署後伺服器上已不存在），需靠前一代快取撐過交接期
        const shells = keys.filter((k) => k.startsWith('ft-shell-') && k !== CACHE).sort();
        shells.pop(); // newest previous generation — keep it
        return Promise.all(shells.map((k) => caches.delete(k)));
      })
      .then(() => self.clients.claim())
  );
});

// 先查當前版本快取（確保拿到最新 shell），舊頁面交接期的舊資源
// 再退回跨快取查找（涵蓋保留的前一代），最後才走網路。
// 資產一律精確匹配 — 回應 URL 與請求 URL 不一致會被模組載入器拒收。
const fromCache = async (request, opts) => {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(request, opts);
  if (hit) return hit;
  const legacy = await caches.match(request, opts);
  return legacy || fetch(request);
};

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Firestore / Finnhub 等跨網域請求一律直接走網路
  if (url.origin !== self.location.origin) return;
  // /finance-tracker/preview/ 是另一個 App（預覽版），不由正式版快取接手
  if (url.pathname.startsWith(PREVIEW_PREFIX)) return;

  if (req.mode === 'navigate') {
    // 導航用 BASE 當快取鍵（忽略 ?utm= 之類參數）
    event.respondWith(fromCache(BASE, { ignoreSearch: true }));
    return;
  }
  if (url.pathname.startsWith(BASE)) {
    event.respondWith(fromCache(req));
  }
});
`
      writeFileSync(join(distDir, 'sw.js'), sw)
      console.log(`[sw-precache] dist/sw.js generated (${urls.length} files, version ${version})`)
    }
  }
}

// https://vite.dev/config/
export default defineConfig({
  plugins: [react(), swPrecachePlugin(), previewManifestPlugin()],
  define: { __FT_PREVIEW__: JSON.stringify(PREVIEW) },
  base: BASE,
  build: {
    rollupOptions: {
      output: {
        manualChunks(id) {
          if (id.includes('node_modules/react-dom') || id.includes('node_modules/react/')) {
            return 'vendor-react';
          }
          if (id.includes('node_modules/firebase/')) {
            return 'vendor-firebase';
          }
          if (id.includes('node_modules/lucide-react/')) {
            return 'vendor-icons';
          }
        }
      }
    }
  }
})
